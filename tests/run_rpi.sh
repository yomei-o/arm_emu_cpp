#!/bin/sh
# Raspberry Pi OS's own binaries: glibc, CPython 3.11 and gcc 12, exactly as
# Raspbian built them.
#
# This is the guest the project was aimed at, and it is a different one from Alpine's
# in two ways that the emulator has to actually satisfy rather than merely survive:
#
#   * **glibc, not musl.** glibc's ARM string routines are the parallel add/subtract
#     instructions -- `uqsub8` against zero to find a zero byte, `sel` to pick the
#     lane out of the GE flags. Those two only work as a pair, and only the
#     *non*-saturating forms write GE. An emulator that implements one and stubs the
#     other returns a string length that is merely somewhere else.
#   * **Raspbian is rebuilt for the original Pi**, so its code does not assume the
#     ARMv7 instructions the Alpine tree uses freely.
#
# `sh guests/fetch_rpi.sh` builds the tree (~250 MB unpacked).
set -e
cd "$(dirname "$0")/.."
EMU=${EMU:-./armemu}
ROOT=guests/rpi
[ -f "$ROOT/usr/bin/python3.11" ] || { echo "skip rpi (no $ROOT -- run: sh guests/fetch_rpi.sh)"; exit 0; }

pass=0; fail=0
check() {   # name, want, got
    if [ "$2" = "$3" ]; then echo "ok   $1"; pass=$((pass+1));
    else echo "FAIL $1"; echo "     want: $2"; echo "     got:  $3"; fail=$((fail+1)); fi
}
# MSYS rewrites a leading-slash argument into a Windows path before the emulator
# sees it. These paths are the *guest's*, so that has to be off.
run() { MSYS_NO_PATHCONV=1 $EMU --root $ROOT "$@" 2>&1 | tr -d '\015'; }

mkdir -p $ROOT/tmp
cp src/cpu.cpp $ROOT/tmp/cpu.cpp

# coreutils, which is where glibc's string routines get their workout.
check "rpi coreutils echo" "hello raspberry pi" "$(run /bin/echo hello raspberry pi)"
check "rpi coreutils sha256sum (against the host's)" \
      "$(sha256sum src/cpu.cpp | tr -d '\015' | cut -d' ' -f1)" \
      "$(run /usr/bin/sha256sum /tmp/cpu.cpp | cut -d' ' -f1)"
check "rpi coreutils wc -l" "$(wc -l < src/cpu.cpp | tr -d ' \015')" \
      "$(run /usr/bin/wc -l /tmp/cpu.cpp | tr -s ' ' | cut -d' ' -f1)"

# CPython 3.11, dynamically linked against that glibc.
check "rpi python version and machine" "3.11.2 armv7l" \
      "$(run /usr/bin/python3.11 -c 'import sys,platform;print(sys.version.split()[0],platform.machine())')"
want=$(python -c "import hashlib;print(hashlib.sha256(b'arm_emu_cpp').hexdigest())" 2>/dev/null \
       || python3 -c "import hashlib;print(hashlib.sha256(b'arm_emu_cpp').hexdigest())")
check "rpi python sha256 (against the host's)" "$want" \
      "$(run /usr/bin/python3.11 -c 'import hashlib;print(hashlib.sha256(b"arm_emu_cpp").hexdigest())')"

# gcc 12: the driver forks cc1, as and collect2/ld, and the binary it links runs
# under the same emulator that built it.
cat > $ROOT/t.c <<'PROG'
#include <stdio.h>
#include <string.h>
static long long fib(int n) { return n < 2 ? n : fib(n - 1) + fib(n - 2); }
int main(void) {
    char buf[64];
    snprintf(buf, sizeof buf, "%lld %.3f", fib(24), 355.0 / 113.0);
    printf("%s %zu\n", buf, strlen(buf));
    return 0;
}
PROG
rm -f $ROOT/t $ROOT/t2
run /usr/bin/gcc-12 -O2 /t.c -o /t > /dev/null
if [ -f "$ROOT/t" ]; then echo "ok   rpi gcc compiles and links"; pass=$((pass+1));
else echo "FAIL rpi gcc compiles and links"; fail=$((fail+1)); fi
check "rpi gcc output runs under the emulator" "46368 3.142 11" "$(run /t)"

# Thumb-2, spelled out in full. Raspbian's gcc defaults to ARMv6, where plain
# `-mthumb` means Thumb-*1* -- and gcc itself refuses that with the hard-float ABI
# ("sorry, unimplemented: Thumb-1 'hard-float' VFP ABI"). Naming `armv7-a` alone then
# fails differently ("selected architecture lacks an FPU"), because an architecture
# name resets the FPU choice and the driver's hard-float ABI has nothing left to use.
# Both are compiler limitations, not emulator ones. `armv7-a+fp` is also the better
# test: it is the encoding a Debian armhf package actually contains.
run /usr/bin/gcc-12 -O2 -mthumb -march=armv7-a+fp /t.c -o /t2 > /dev/null
check "rpi gcc -mthumb (Thumb-2) output runs" "46368 3.142 11" "$(run /t2)"

# ---- NEON, generated by the guest's own compiler ------------------------------
#
# The same source compiled twice by the emulated gcc -- once with the vectoriser and
# NEON on, once with both off -- and the two runs must agree. That is a stronger test
# than a hand-written one and a cheaper one to maintain: gcc picks the instructions,
# so the coverage follows whatever a real compiler actually emits, and the scalar
# build is an oracle that needs no host compiler at all.
#
# It found four separate NEON bugs the first time it was run, every one of which
# produced a plausible number rather than a fault:
#   * the three-registers-same-length group ignored bit 24, which is U -- so the
#     whole unsigned half of NEON was refused
#   * VQADD/VQSUB did not saturate and VHADD/VHSUB ignored signedness
#   * VBSL read Vn as the mask instead of the destination, inverting every select
#   * VMOVL halved its element size, widening bytes where it was asked for halfwords
cat > $ROOT/vec.c <<'PROG'
#include <stdio.h>
#include <stdint.h>
#define N 512
static int32_t  ai[N], bi[N], ci[N];
static float    af[N], bf[N], cf[N];
static uint8_t  ab[N], bb[N], cb[N];
static int16_t  ah[N], bh[N], ch[N];
static int32_t  wi[N];
static int16_t  nh[N];
static uint64_t fnv(const void* p, int n) {
    const uint8_t* b = (const uint8_t*)p;
    uint64_t h = 1469598103934665603ull;
    for (int i = 0; i < n; i++) { h ^= b[i]; h *= 1099511628211ull; }
    return h;
}
#define SHOW(tag, buf) printf("%-12s %016llx\n", tag, (unsigned long long)fnv(buf, sizeof buf))
volatile int32_t k32 = 37;
volatile int16_t k16 = -13;
volatile float   kf  = 1.75f;
static uint8_t  cb2[512];
int main(void) {
    for (int i = 0; i < N; i++) {
        ai[i] = i * 7919 - 100000; bi[i] = (i * 31) % 251 - 125;
        af[i] = i * 0.5f - 64.0f;  bf[i] = (i % 17) + 0.25f;
        ab[i] = (uint8_t)(i * 13); bb[i] = (uint8_t)(i * 7 + 3);
        ah[i] = (int16_t)(i * 811 - 30000); bh[i] = (int16_t)((i * 17) % 97 - 48);
    }
    for (int i = 0; i < N; i++) ci[i] = ai[i] + bi[i] * 3;                 SHOW("i32 mla", ci);
    for (int i = 0; i < N; i++) cf[i] = af[i] * bf[i] + 1.5f;              SHOW("f32 mla", cf);
    for (int i = 0; i < N; i++) cb[i] = (uint8_t)(ab[i] > bb[i] ? ab[i] - bb[i] : 0);
                                                                          SHOW("u8 sat", cb);
    for (int i = 0; i < N; i++) ch[i] = (int16_t)(ah[i] > bh[i] ? ah[i] : bh[i]);
                                                                          SHOW("s16 max", ch);
    for (int i = 0; i < N; i++) cb[i] = (uint8_t)(ab[i] < bb[i] ? ab[i] : bb[i]);
                                                                          SHOW("u8 min", cb);
    for (int i = 0; i < N; i++) wi[i] = (int32_t)ah[i] * 3;                SHOW("s16->32", wi);
    for (int i = 0; i < N; i++) nh[i] = (int16_t)(ai[i] >> 5);             SHOW("s32->16", nh);
    for (int i = 0; i < N; i++) ci[i] = ai[i] >> 3;                        SHOW("s32 shr", ci);
    for (int i = 0; i < N; i++) ci[i] = (int32_t)((uint32_t)ai[i] << 2);   SHOW("i32 shl", ci);
    for (int i = 0; i < N; i++) ch[i] = (int16_t)(ah[i] < 0 ? -ah[i] : ah[i]);
                                                                          SHOW("s16 abs", ch);
    for (int i = 0; i < N; i++) cb[i] = (uint8_t)((ab[i] + bb[i] + 1) >> 1);
                                                                          SHOW("u8 rhadd", cb);
    { int64_t s = 0; for (int i = 0; i < N; i++) s += ai[i];
      printf("%-10s %016llx\n", "i32 sum", (unsigned long long)s); }
    { float s = 0; for (int i = 0; i < N; i++) s += af[i] * bf[i];
      uint32_t fb; __builtin_memcpy(&fb, &s, 4);
      printf("%-10s %016llx\n", "f32 dot", (unsigned long long)fb); }
    { uint32_t s = 0; for (int i = 0; i < N; i++) s += ab[i] > bb[i] ? ab[i] - bb[i] : bb[i] - ab[i];
      printf("%-10s %016llx\n", "u8 sad", (unsigned long long)s); }
    for (int i = 0; i < N; i++) cf[i] = (float)ai[i] * 0.25f;              SHOW("i32->f32", cf);
    for (int i = 0; i < N; i++) ci[i] = (int32_t)(af[i] * 4.0f);           SHOW("f32->i32", ci);
    { int32_t k = k32; for (int i = 0; i < N; i++) ci[i] = ai[i] * k; }        SHOW("i32 mul-k", ci);
    { int16_t k = k16; for (int i = 0; i < N; i++) ch[i] = (int16_t)(ah[i] * k); } SHOW("s16 mul-k", ch);
    { float k = kf;  for (int i = 0; i < N; i++) cf[i] = af[i] * k; }          SHOW("f32 mul-k", cf);
    { int32_t k = k32; for (int i = 0; i < N; i++) ci[i] += ah[i] * k; }       SHOW("i32 mla-k", ci);
    /* narrowing with saturation */
    for (int i = 0; i < N; i++) {
        int32_t v = ai[i] >> 4;
        ch[i] = (int16_t)(v > 32767 ? 32767 : (v < -32768 ? -32768 : v));
    }                                                                          SHOW("s32->s16 q", ch);
    for (int i = 0; i < N; i++) {
        int32_t v = ai[i] >> 4;
        cb[i] = (uint8_t)(v > 255 ? 255 : (v < 0 ? 0 : v));
    }                                                                          SHOW("s32->u8 q", cb);
    /* interleaved load/store: VLD2/VST2 shapes */
    for (int i = 0; i < N / 2; i++) { ci[i * 2] = ai[i]; ci[i * 2 + 1] = ai[N / 2 + i]; }
                                                                               SHOW("interleave", ci);
    /* byte reverse and table-ish gather */
    for (int i = 0; i < N; i++) cb[i] = ab[N - 1 - i];                          SHOW("reverse", cb);
    return 0;
}
PROG
rm -f $ROOT/vecn $ROOT/vecs
run /usr/bin/gcc-12 -O3 -march=armv7-a+neon -mfpu=neon -ftree-vectorize /vec.c -o /vecn > /dev/null
run /usr/bin/gcc-12 -O1 -fno-tree-vectorize /vec.c -o /vecs > /dev/null
neon=$(run /vecn)
scalar=$(run /vecs)
check "rpi gcc -mfpu=neon output matches the scalar build" "$scalar" "$neon"

echo "$pass passed, $fail failed"
[ "$fail" -eq 0 ]
